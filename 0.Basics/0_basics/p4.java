// finding length of given string 

class Solution {

        public int findLength(String s ){
            return s.length();

        }
    }

public class p4 {
    // strings 
    public static void main(String[] args) {
        Solution obj = new Solution(); 

        String s  = " Hello World "; 

        System.out.println( obj.findLength (s));
        
    }
    


}

